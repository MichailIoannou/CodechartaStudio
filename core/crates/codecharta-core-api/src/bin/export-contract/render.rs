use std::collections::BTreeSet;

use codecharta_core_api::PROTOCOL_VERSION;
use codecharta_core_api::error::{ErrorCode, ErrorPayload};
use codecharta_core_api::protocol::RequestId;
use codecharta_core_api::registry::{
    Audience, CLIENT_NOTIFICATIONS, EVENTS, EventSpec, METHODS, TypeExport,
};
use ts_rs::{Config, ExportError};

const GENERATED_HEADER: &str = "// This file was generated by export-contract from codecharta-core-api. Do not edit this file manually.";
const TYPESCRIPT_EXTENSION: &str = ".ts";

pub fn contract_types() -> Vec<TypeExport> {
    let for_the_renderer = [
        TypeExport::of::<ErrorPayload>(),
        TypeExport::of::<RequestId>(),
    ];
    referenced_types()
        .into_iter()
        .chain(for_the_renderer)
        .collect()
}

fn referenced_types() -> Vec<TypeExport> {
    let method_types = METHODS.iter().flat_map(|spec| [spec.params, spec.result]);
    let event_types = EVENTS
        .iter()
        .chain(CLIENT_NOTIFICATIONS)
        .map(|spec| spec.params);
    std::iter::once(TypeExport::of::<ErrorCode>())
        .chain(method_types)
        .chain(event_types)
        .filter(TypeExport::is_named)
        .collect()
}

pub fn export_types(config: &Config) -> Result<(), ExportError> {
    contract_types()
        .iter()
        .try_for_each(|export| (export.export_all)(config))
}

pub fn shell_allow_list() -> String {
    let allow_list = serde_json::json!({
        "protocolVersion": PROTOCOL_VERSION,
        "rendererMethods": renderer_method_names(),
        "rendererEvents": renderer_event_names(),
    });
    format!("{allow_list:#}\n")
}

pub fn renderer_method_names() -> Vec<&'static str> {
    METHODS
        .iter()
        .filter(|spec| spec.audience == Audience::Renderer)
        .map(|spec| spec.name)
        .collect()
}

pub fn renderer_event_names() -> Vec<&'static str> {
    EVENTS
        .iter()
        .filter(|spec| spec.audience == Audience::Renderer)
        .map(|spec| spec.name)
        .collect()
}

pub fn core_api_module(config: &Config) -> String {
    [
        GENERATED_HEADER.to_string(),
        imports(config),
        format!("export const CORE_PROTOCOL_VERSION = {PROTOCOL_VERSION}"),
        error_codes(),
        method_map(config),
        event_map("CoreEvents", EVENTS, config),
        event_map("CoreClientNotifications", CLIENT_NOTIFICATIONS, config),
        name_list(
            "RENDERER_METHODS",
            "RendererMethod",
            "CoreMethods",
            &renderer_method_names(),
        ),
        name_list(
            "RENDERER_EVENTS",
            "RendererEvent",
            "CoreEvents",
            &renderer_event_names(),
        ),
    ]
    .join("\n\n")
        + "\n"
}

fn imports(config: &Config) -> String {
    let lines: BTreeSet<String> = referenced_types()
        .iter()
        .filter_map(|export| import_line(export, config))
        .collect();
    lines.into_iter().collect::<Vec<_>>().join("\n")
}

fn import_line(export: &TypeExport, config: &Config) -> Option<String> {
    let output_path = (export.output_path)()?;
    let module = output_path
        .to_str()?
        .strip_suffix(TYPESCRIPT_EXTENSION)?
        .replace('\\', "/");
    Some(format!(
        "import type {{ {} }} from \"./{module}\"",
        (export.name)(config)
    ))
}

fn error_codes() -> String {
    let codes: Vec<String> = ErrorCode::ALL
        .iter()
        .map(|code| serde_json::json!(code).to_string())
        .collect();
    format!(
        "export const CORE_ERROR_CODES = [{}] as const satisfies ReadonlyArray<ErrorCode>",
        codes.join(", ")
    )
}

fn method_map(config: &Config) -> String {
    let entries: Vec<String> = METHODS
        .iter()
        .map(|spec| {
            format!(
                "    \"{}\": {{ params: {}; result: {} }}",
                spec.name,
                (spec.params.name)(config),
                (spec.result.name)(config)
            )
        })
        .collect();
    format!("export type CoreMethods = {{\n{}\n}}", entries.join("\n"))
}

fn event_map(type_name: &str, specs: &[EventSpec], config: &Config) -> String {
    let entries: Vec<String> = specs
        .iter()
        .map(|spec| format!("    \"{}\": {}", spec.name, (spec.params.name)(config)))
        .collect();
    format!("export type {type_name} = {{\n{}\n}}", entries.join("\n"))
}

fn name_list(constant: &str, union: &str, map: &str, names: &[&str]) -> String {
    let quoted: Vec<String> = names.iter().map(|name| format!("\"{name}\"")).collect();
    format!(
        "export const {constant} = [{}] as const satisfies ReadonlyArray<keyof {map}>\n\nexport type {union} = (typeof {constant})[number]",
        quoted.join(", ")
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn should_list_only_renderer_methods_in_the_allow_list() {
        // Arrange
        let expected: Vec<&str> = METHODS
            .iter()
            .filter(|spec| spec.audience == Audience::Renderer)
            .map(|spec| spec.name)
            .collect();

        // Act
        let allow_list: serde_json::Value = serde_json::from_str(&shell_allow_list()).unwrap();

        // Assert
        assert_eq!(allow_list["rendererMethods"], serde_json::json!(expected));
        assert_eq!(
            allow_list["protocolVersion"],
            serde_json::json!(PROTOCOL_VERSION)
        );
        let listed = allow_list["rendererMethods"].as_array().unwrap();
        assert!(!listed.contains(&serde_json::json!("core.hello")));
        assert!(!listed.contains(&serde_json::json!("core.shutdown")));
    }

    #[test]
    fn should_emit_a_method_map_entry_per_registered_method() {
        // Arrange
        let config = Config::new().with_large_int("number");

        // Act
        let module = core_api_module(&config);

        // Assert
        let missing: Vec<&str> = METHODS
            .iter()
            .map(|spec| spec.name)
            .filter(|name| !module.contains(&format!("\"{name}\": {{ params: ")))
            .collect();
        assert!(missing.is_empty(), "missing: {missing:?}");
        assert!(module.contains("\"core.hello\": { params: HelloParams; result: HelloResult }"));
        assert!(module.contains("\"core.shutdown\": { params: EmptyParams; result: null }"));
    }

    #[test]
    fn should_import_each_named_type_once() {
        // Arrange
        let config = Config::new().with_large_int("number");

        // Act
        let module = core_api_module(&config);

        // Assert
        assert_eq!(
            module
                .matches("import type { EmptyParams } from \"./EmptyParams\"")
                .count(),
            1
        );
        assert!(!module.contains("import type { null }"));
        assert!(!module.contains("import type { ErrorPayload }"));
    }

    #[test]
    fn should_list_every_error_code() {
        // Arrange
        let config = Config::new();

        // Act
        let module = core_api_module(&config);

        // Assert
        assert!(module.contains("\"BAD_REQUEST\", \"NOT_FOUND\""));
        assert!(module.contains("\"INTERNAL\"] as const"));
    }
}
